import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..");
const sourceDir = join(repoRoot, "local-data", "linkedin");
const outputPath = join(repoRoot, "src", "data", "linkedinFeed.ts");

const months = new Map(
  [
    "January",
    "February",
    "March",
    "April",
    "May",
    "June",
    "July",
    "August",
    "September",
    "October",
    "November",
    "December"
  ].map((month, index) => [month, index])
);

function parseCsv(text) {
  const rows = [];
  let field = "";
  let row = [];
  let quoted = false;

  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    const next = text[index + 1];

    if (char === '"' && quoted && next === '"') {
      field += '"';
      index += 1;
      continue;
    }

    if (char === '"') {
      quoted = !quoted;
      continue;
    }

    if (char === "," && !quoted) {
      row.push(field);
      field = "";
      continue;
    }

    if ((char === "\n" || char === "\r") && !quoted) {
      if (char === "\r" && next === "\n") index += 1;
      row.push(field);
      if (row.some((value) => value.trim() !== "")) rows.push(row);
      row = [];
      field = "";
      continue;
    }

    field += char;
  }

  if (field.length > 0 || row.length > 0) {
    row.push(field);
    if (row.some((value) => value.trim() !== "")) rows.push(row);
  }

  return rows;
}

function parseLinkedInDate(value) {
  const match = value.match(
    /on ([A-Za-z]+) (\d{1,2}), (\d{4}) at (\d{1,2}):(\d{2}) (AM|PM) \(GMT\)/
  );
  if (!match) return null;

  const [, monthName, dayText, yearText, hourText, minuteText, meridiem] = match;
  const month = months.get(monthName);
  if (month === undefined) return null;

  let hour = Number(hourText);
  if (meridiem === "PM" && hour !== 12) hour += 12;
  if (meridiem === "AM" && hour === 12) hour = 0;

  return new Date(
    Date.UTC(Number(yearText), month, Number(dayText), hour, Number(minuteText))
  );
}

function titleCaseKind(value) {
  return value
    .replace(/^feed /, "")
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

if (!existsSync(sourceDir)) {
  throw new Error(`Missing LinkedIn export folder: ${sourceDir}`);
}

const archive = readdirSync(sourceDir)
  .filter((name) => name.toLowerCase().endsWith(".zip") || name.toLowerCase().endsWith(".zip.zip"))
  .sort()
  .at(-1);

if (!archive) {
  throw new Error(`No LinkedIn export ZIP found in ${sourceDir}`);
}

const richMediaCsv = execFileSync(
  "tar",
  ["-xOf", join(sourceDir, archive), "Rich_Media.csv"],
  { encoding: "utf8" }
);

const [header, ...rows] = parseCsv(richMediaCsv);
const columns = new Map(header.map((name, index) => [name, index]));

const items = rows
  .map((row) => {
    const event = row[columns.get("Date/Time")]?.trim() || "";
    const description = row[columns.get("Media Description")]?.trim() || "";
    const url = row[columns.get("Media Link")]?.trim() || "";
    const kind = event.match(/uploaded a (.+?) on/)?.[1] || "media";
    const date = parseLinkedInDate(event);

    return {
      date: date?.toISOString() || "",
      kind,
      title: titleCaseKind(kind),
      description: description === "-" ? "" : description,
      url
    };
  })
  .filter((item) => item.date && item.url && item.kind.startsWith("feed "))
  .sort((a, b) => b.date.localeCompare(a.date));

const generated = `// Generated by scripts/sync-linkedin-feed.mjs from local-data/linkedin/.
// Keep the raw LinkedIn export out of public assets and source control.

export interface LinkedInFeedItem {
  date: string;
  kind: string;
  title: string;
  description: string;
  url: string;
}

export const linkedinFeedItems: LinkedInFeedItem[] = ${JSON.stringify(items, null, 2)};
`;

writeFileSync(outputPath, generated);
console.log(`Wrote ${items.length} LinkedIn feed items to ${outputPath}`);
